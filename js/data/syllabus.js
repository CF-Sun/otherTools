/* 便利索引 */
(function () {
  const IPAS = window.IPAS;
  IPAS.itemIndex = {};
  IPAS.subjects.forEach((s) =>
    s.themes.forEach((t) =>
      t.items.forEach((it) => {
        IPAS.itemIndex[it.id] = Object.assign({ subject: s, theme: t }, it);
      })
    )
  );
  IPAS.subjectById = Object.fromEntries(IPAS.subjects.map((s) => [s.id, s]));
  IPAS.itemsOf = (sid) => IPAS.subjectById[sid].themes.flatMap((t) => t.items);
})();
